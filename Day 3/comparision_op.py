# Comparisio Operator: operator used to compare values
a = 10
b = 10

# equal to (==): checks if given data are equal or not, if equal output: True, if not equal output: False
print(a == b)

# not equal to (!=): checks if given data are equal or not, if equal output: False, if not equal output: True
print(a != b)

# greather than (>): if a is greater than b, Ouput: True, else Output: False
print(a > b)

# less than (<): if a is less than b, Ouput: False, else Output: True
print(a < b)

# greather than or equal to (>=): if a is greater than or equal b, Ouput: True, else Output: False
print(a >= b)

# less than or equal to (<=): if a is less than or equal to b, Ouput: False, else Output: True
print(a <= b)