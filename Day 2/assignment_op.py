# Assignment operator: this operator is used to assign data/values in variables
# ewual to (=):
a = 10

# add and assign(+=)
a += 10 #a = a + 10 = 10 + 10 = 20
print(a)

# -=
a -= 5 #a = a - 5 = 10 - 5 = 5
print(a)

# *=
a *= 3
print(a)

# /=
a /= 5
print(a)

# //=
a //= 2
print(a)

# %=
a %= 3
print(a)

# **= 
a **= 1
print(a)