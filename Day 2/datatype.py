# Group datatypes:
# List: [] used to define list, multiple data of multiple datatype can be defined, ordered, mutable(changable)
my_list = ["hello", 15, 52, 4, True, None, "hii", "500"]
print(my_list)

# Tuple: () used tp define list, multiple data of multiple datatype can be defined, ordered, unmutable(unchangable)
my_tuple = ("hello", 15, 52, 4, True, None, "hii", "500")
print(my_tuple)

# Set: {} used to define set, multiple data of multiple datatype, unordered, does not contain duplicate data
my_set = {"hellp", 50, 16.6, "hi", 90, 50}
